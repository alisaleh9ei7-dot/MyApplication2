package com.example.myapplication.data.v8.error

/** Stable error vocabulary shared by V8 database triggers and Kotlin services. */
enum class V8ErrorCode(val token: String) {
    INSUFFICIENT_STOCK("E_INSUFFICIENT_STOCK"),
    BATCH_OVERFLOW("E_BATCH_OVERFLOW"),
    NEGATIVE_BATCH_BALANCE("E_NEGATIVE_BATCH_BALANCE"),
    COST_OUT_OF_RANGE("E_COST_OUT_OF_RANGE"),
    ZERO_QTY_WITH_COST("E_ZERO_QTY_WITH_COST"),
    BATCH_SOURCE_NOT_SUPPORTED("E_BATCH_SOURCE_NOT_SUPPORTED"),
    BATCH_FACTOR_MISMATCH("E_BATCH_FACTOR_MISMATCH"),
    BATCH_FACTOR_IMMUTABLE("E_BATCH_FACTOR_IMMUTABLE"),
    SALE_NOT_FOUND("E_SALE_NOT_FOUND"),
    SALE_NOT_PENDING("E_SALE_NOT_PENDING"),
    SALE_NOT_CONFIRMED("E_SALE_NOT_CONFIRMED"),
    SALE_ALREADY_CANCELLED("E_SALE_ALREADY_CANCELLED"),
    SALE_LINE_BASE_QTY_MISMATCH("E_SALE_LINE_BASE_QTY_MISMATCH"),
    SALE_LINE_SNAPSHOT_IMMUTABLE("E_SALE_LINE_SNAPSHOT_IMMUTABLE"),
    SALE_REVERSAL_MISMATCH("E_SALE_REVERSAL_MISMATCH"),
    SALE_REVERSAL_ALREADY_EXISTS("E_SALE_REVERSAL_ALREADY_EXISTS"),
    SALE_RECONCILIATION_FAILED("E_SALE_RECONCILIATION_FAILED"),
    PURCHASE_LINE_FACTOR_MISMATCH("E_PURCHASE_LINE_FACTOR_MISMATCH"),
    PURCHASE_LINE_IMMUTABLE("E_PURCHASE_LINE_IMMUTABLE"),
    ITEM_FACTOR_LOCKED_BY_STOCK("E_ITEM_FACTOR_LOCKED_BY_STOCK"),
    INVALID_ITEM_CHANGE("E_INVALID_ITEM_CHANGE"),
    ITEM_CHANGE_IMMUTABLE("E_ITEM_CHANGE_IMMUTABLE"),
    MOVEMENT_TYPE_NOT_SUPPORTED("E_MOVEMENT_TYPE_NOT_SUPPORTED"),
    OPENING_MOVEMENT_INVALID("E_OPENING_MOVEMENT_INVALID"),
    MOVEMENT_IMMUTABLE("E_MOVEMENT_IMMUTABLE"),
    RECORD_DELETE_NOT_ALLOWED("E_RECORD_DELETE_NOT_ALLOWED"),
    PURCHASE_DELETE_NOT_ALLOWED("E_PURCHASE_DELETE_NOT_ALLOWED"),
    PURCHASE_LINE_DELETE_NOT_ALLOWED("E_PURCHASE_LINE_DELETE_NOT_ALLOWED"),
    INVALID_STRIPS_PER_BOX("E_INVALID_STRIPS_PER_BOX"),
    ITEM_DELETE_NOT_ALLOWED("E_ITEM_DELETE_NOT_ALLOWED"),
    DATABASE_READ_ONLY("E_DATABASE_READ_ONLY"),
    DATABASE_INTEGRITY_FAILED("E_DATABASE_INTEGRITY_FAILED"),
    FOREIGN_KEY_VIOLATION("E_FOREIGN_KEY_VIOLATION"),
    TRIGGER_REPAIR_FAILED("E_TRIGGER_REPAIR_FAILED");

    companion object {
        private val byToken = entries.associateBy(V8ErrorCode::token)
        fun fromToken(token: String): V8ErrorCode? = byToken[token]
    }
}

sealed interface SaleError {
    data class Known(
        val code: V8ErrorCode,
        val rawMessage: String,
        val cause: Throwable?
    ) : SaleError

    data class Unknown(
        val rawMessage: String,
        val cause: Throwable?
    ) : SaleError
}
